"""Descriptive statistics for the data paper (reproducible; no API calls).

    python tools/paper_stats.py      # writes docs/paper/stats.md and docs/paper/stats.json

Reads registry/instruments.jsonl, registry/triage.jsonl, registry/families.jsonl, annotations/*.json and, if
present, ../econ-semantic-extraction/outputs/corroboration/candidates.csv.
"""

from __future__ import annotations

import csv
import json
from collections import Counter, defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "docs" / "paper"


def year(d):
    return int(d[:4]) if d and d[:4].isdigit() else None


def main() -> None:
    reg = [json.loads(l) for l in (ROOT / "registry" / "instruments.jsonl").open()]
    tri = {json.loads(l)["instrument_id"]: json.loads(l) for l in (ROOT / "registry" / "triage.jsonl").open()}
    fam = [json.loads(l) for l in (ROOT / "registry" / "families.jsonl").open()]
    ann = [json.loads(p.read_text()) for p in sorted((ROOT / "annotations").glob("*.json"))]
    S, md = {}, ["# Descriptive statistics for the data paper", "",
                 "Generated by `tools/paper_stats.py` from the registry and `annotations/`. Machine annotations "
                 "(Haiku 5.5) except 26 gold; see `docs/validation_log.md` for accuracy.", ""]

    def table(title, counter, n=None, top=None):
        items = counter.most_common(top) if top else sorted(counter.items(), key=lambda x: (-x[1], str(x[0])))
        md.extend([f"## {title}", "", "| | n |", "|---|---|"] + [f"| {k} | {v} |" for k, v in items] + [""])
        S[title] = dict(items)

    # ---- coverage
    table("Registry by priority region", Counter(r.get("priority_region") for r in reg))
    table("Registry by legislative stage", Counter(r.get("legislative_stage") for r in reg))
    table("Registry by instrument type", Counter(r.get("instrument_type") for r in reg))
    table("Registry by level", Counter(r.get("level") for r in reg))
    dom = Counter(d for r in reg for d in r.get("domains", []))
    table("Registry by domain (multi-label)", dom)
    table("Triage tiers", Counter(t["tier"] for t in tri.values()))
    table("Tier A by region", Counter(next((r["priority_region"] for r in reg if r["instrument_id"] == i), "?")
                                      for i, t in tri.items() if t["tier"] == "A"))
    gates = Counter()
    for t in tri.values():
        if t["tier"] == "C":
            g = t["gates"]
            gates["not binding" if not g["binding"] else "no private reach" if not g["private_reach"]
                  else f"stage {t['legislative_stage']}, score {sum(t.get('scores', {}).values())}"
                  if t["legislative_stage"] in ("dead", "introduced") else "low score"] += 1
    table("Why Tier C (registry only)", gates, top=8)
    table("Decision margins acted on (triage, Tier A+B)",
          Counter(m for t in tri.values() if t["tier"] in "AB" for m in t.get("decision_margins", [])))

    # ---- evolution over time
    by_year = defaultdict(Counter)
    for r in reg:
        y = year(r.get("dates", {}).get("adopted")) or year(r.get("dates", {}).get("proposed"))
        if y and 2015 <= y <= 2026:
            by_year[y][r.get("legislative_stage")] += 1
    md += ["## Instruments by year (adopted date, else proposed) and stage", "",
           "| year | adopted | advanced | introduced | dead |", "|---|---|---|---|---|"]
    for y in sorted(by_year):
        c = by_year[y]
        md.append(f"| {y} | {c['adopted']} | {c['advanced']} | {c['introduced']} | {c['dead']} |")
    md.append("")
    S["by_year"] = {y: dict(c) for y, c in by_year.items()}
    dc = defaultdict(Counter)
    for r in reg:
        y = year(r.get("dates", {}).get("adopted")) or year(r.get("dates", {}).get("proposed"))
        if y and 2015 <= y <= 2026:
            for d in r.get("domains", []):
                if d in ("compute_data_centers", "energy_grid_water", "generative_ai", "ai_general",
                         "chips_export_controls", "synthetic_media_deepfakes"):
                    dc[d][y] += 1
    md += ["## Selected domains by year", "", "| domain | " + " | ".join(str(y) for y in range(2018, 2027)) + " |",
           "|---|" + "---|" * 9]
    for d, c in sorted(dc.items()):
        md.append(f"| {d} | " + " | ".join(str(c[y]) for y in range(2018, 2027)) + " |")
    md.append("")
    S["domains_by_year"] = {d: dict(c) for d, c in dc.items()}

    # ---- annotation content
    machine = [a for a in ann if "gold" not in a["annotator"].get("prompt_version", "gold")]
    md += [f"## Annotation content ({len(ann)} annotations: {Counter(a['tier'] for a in ann)})", ""]
    n_items = Counter()
    for a in ann:
        for s in ("events", "thresholds", "obligations", "enforcement", "definitions", "relations", "entities"):
            n_items[s] += len(a.get(s, []))
    table("Annotated items by section", n_items)
    thr = [t for a in ann for t in a.get("thresholds", [])]
    table("Threshold variables", Counter(t.get("variable") for t in thr), top=15)
    table("Threshold triggers", Counter(t.get("trigger") for t in thr), top=12)
    vals = Counter()
    for t in thr:
        if isinstance(t.get("value"), (int, float)) and t.get("unit"):
            vals[f"{t['value']:g} {t['unit']}"[:60]] += 1
    table("Most frequent threshold values (value + unit)", vals, top=20)
    obl = [o for a in ann if a["tier"] == "A" for o in a.get("obligations", [])]
    table("Obligations by addressee role (Tier A)", Counter(o.get("addressee") for o in obl), top=15)
    table("Obligations by type (Tier A)", Counter(o.get("type") for o in obl), top=15)
    enf = [e for a in ann for e in a.get("enforcement", [])]
    table("Sanction types", Counter(e.get("sanction_type") or e.get("type") for e in enf), top=12)
    turnover = sum(1 for a in ann if any("turnover" in json.dumps(e).lower() or "revenue" in json.dumps(e).lower()
                                         for e in a.get("enforcement", [])))
    pra = sum(1 for a in ann if any(e.get("private_right_of_action") is True for e in a.get("enforcement", [])))
    md += [f"- Laws with a turnover- or revenue-based fine formula: {turnover}", f"- Laws with a private right of "
           f"action: {pra}", ""]
    S["turnover_fine_laws"], S["private_right_laws"] = turnover, pra
    ev = [e for a in ann for e in a.get("events", [])]
    table("Event types", Counter(e.get("event") for e in ev), top=15)
    lag = []
    for a in ann:
        d = {e["event"]: e["date"] for e in a.get("events", []) if e.get("date") and len(str(e["date"])) == 10}
        if "adopted" in d and "application" in d:
            from datetime import date
            lag.append((date.fromisoformat(d["application"]) - date.fromisoformat(d["adopted"])).days)
    if lag:
        lag.sort()
        md += [f"- Adoption → (first) application date: n={len(lag)}, median {lag[len(lag) // 2]} days, "
               f"p25 {lag[len(lag) // 4]}, p75 {lag[3 * len(lag) // 4]}", ""]
        S["adoption_to_application_days"] = {"n": len(lag), "median": lag[len(lag) // 2]}
    rel = [r for a in ann for r in a.get("relations", [])]
    table("Relation types", Counter(r.get("relation") or r.get("type") for r in rel), top=12)
    table("Families (diffusion panels)", Counter({f["family_id"]: len(f["members"]) for f in fam}))

    # ---- causal designs
    cand = ROOT.parent / "econ-semantic-extraction" / "outputs" / "corroboration" / "candidates.csv"
    if cand.exists():
        rows = list(csv.DictReader(cand.open()))
        table("Causal designs by strength (Opus corroboration)", Counter(r["strength"] for r in rows))
        table("Causal designs (strength >= 3) by design", Counter(r["design"] for r in rows if int(r["strength"]) >= 3))
        md += ["## Strongest designs (strength >= 4)", "", "| law | design | strength | title |", "|---|---|---|---|"]
        for r in rows:
            if int(r["strength"]) >= 4:
                md.append(f"| {r['document_id']} | {r['design']} | {r['strength']} | {r['title'][:100]} |")
        md.append("")
    OUT.mkdir(parents=True, exist_ok=True)
    (OUT / "stats.md").write_text("\n".join(md))
    (OUT / "stats.json").write_text(json.dumps(S, indent=1, default=str))
    print(f"wrote {OUT / 'stats.md'} ({len(md)} lines)")


if __name__ == "__main__":
    main()
